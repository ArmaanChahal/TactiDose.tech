# --------------------------------------------------------------------------- helpers


def _days(days: int) -> str:
    return f"{days} day" if days == 1 else f"{days} days"


def _fit_text(pdf: FPDF, text: str, width: float) -> str:
    """``text`` shortened with an ellipsis so it fits ``width`` in the current font."""
    if pdf.get_string_width(text) <= width:
        return text
    lo, hi = 0, len(text)
    while lo < hi:                      # longest prefix that fits together with the ellipsis
        mid = (lo + hi + 1) // 2
        if pdf.get_string_width(text[:mid].rstrip() + "…") <= width:
            lo = mid
        else:
            hi = mid - 1
    return text[:lo].rstrip() + "…"


def _supply_text(value: float | None) -> str:
    if value is None:
        return "–"
    if value >= 100:
        return f"{value:.0f}"
    return f"{value:.1f}".rstrip("0").rstrip(".") if value % 1 else f"{value:.0f}"


def _per_day_text(value: float) -> str:
    if not value:
        return "0"
    return f"{value:.2f}".rstrip("0").rstrip(".")


def _bars_to_label(rows: Sequence[dict[str, Any]]) -> set[int]:
    """Direct labels only where they matter: the latest day with data and the days below 100%
    (or just the lowest one when there are many)."""
    idx = [i for i, r in enumerate(rows) if r["adherence_rate"] is not None]
    if not idx:
        return set()
    chosen = {idx[-1]}
    below = [i for i in idx if rows[i]["adherence_rate"] < 1]
    if len(below) <= 6:
        chosen.update(below)
    else:
        chosen.add(min(below, key=lambda i: (rows[i]["adherence_rate"], i)))
    return chosen
