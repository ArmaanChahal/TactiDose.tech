    def _refused(self) -> None:
        self._heading("Refused requests")
        drops = self.stats["drops"]
        refused = [d for d in self.data.drops if d.status == "DENIED" and d.source != "schedule"]
        skipped = [d for d in self.data.drops if d.status == "DENIED" and d.source == "schedule"]
        if not refused:
            self._note("No drop request was refused in this period.")
        else:
            self._note("A safety rule turned these requests down, so nothing was dropped.")
            reason_rows = [[reason_label(r), n] for r, n in drops["refused_by_reason"].items()]
            if reason_rows:
                self._table(["Reason", "Requests"], reason_rows, (4, 1), ("LEFT", "RIGHT"), width=110)
            recent = refused[-30:]
            rows = []
            for d in recent:
                med = d.medication_name or "–"
                if d.container_number:
                    med += f" (container {d.container_number})"
                rows.append([fmt_datetime(self._local(d.requested_at)), source_label(d.source), med,
                             reason_label(d.reason)])
            self._table(["When", "Via", "Medication", "Reason"], rows, (5, 3, 8, 9), ("LEFT",) * 4)
            if len(refused) > len(recent):
                self._note(f"Showing the latest {len(recent)} of {len(refused)} refused requests.")
        if skipped:
            by_reason: dict[str, int] = {}
            for d in skipped:
                by_reason[reason_label(d.reason)] = by_reason.get(reason_label(d.reason), 0) + 1
            parts = ", ".join(f"{k}: {v}" for k, v in sorted(by_reason.items(), key=lambda kv: -kv[1]))
            self._note(f"Automatic scheduled drops skipped by the rules: {len(skipped)} ({parts}).")

