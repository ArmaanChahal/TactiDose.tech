def _first(dirs: Sequence[Path], name: str) -> Path | None:
    for d in dirs:
        p = d / name
        try:
            if p.is_file():
                return p
        except OSError:
            continue
    return None


def _ttc_face(path: Path, want_bold: bool) -> int:
    """Face index of the (non-italic) regular or bold member of a .ttc collection (0 if unknown)."""
    if path.suffix.lower() != ".ttc":
        return 0
    try:
        from fontTools.ttLib import TTCollection

        coll = TTCollection(str(path), lazy=True)
        for i, font in enumerate(coll.fonts):
            sub = (font["name"].getDebugName(2) or "").strip().lower()
            if sub == ("bold" if want_bold else "regular"):
                return i
    except Exception:  # noqa: BLE001 - unreadable collection: use the first face
        return 0
    return 0


@lru_cache(maxsize=1)
def find_system_fonts() -> FontPaths:
    """Best available OS fonts (cached; cheap filesystem checks only)."""
    if sys.platform.startswith("win"):
        dirs, primary, fallback = _win_dirs(), _WIN_PRIMARY, _WIN_FALLBACK
    elif sys.platform == "darwin":
        dirs, primary, fallback = _mac_dirs(), _MAC_PRIMARY, _MAC_FALLBACK
    else:
        dirs, primary, fallback = _linux_dirs(), _LINUX_PRIMARY, _LINUX_FALLBACK
    regular = bold = None
    for reg_name, bold_name in primary:
        reg = _first(dirs, reg_name)
        if reg is None:
            continue
        regular = FontFile(reg, _ttc_face(reg, False))
        b = _first(dirs, bold_name) if bold_name else None
        bold = FontFile(b, _ttc_face(b, True)) if b is not None else None
        break
    if regular is None and not sys.platform.startswith("win") and sys.platform != "darwin":
        regular = _search_linux_dejavu(dirs)
    fallbacks: list[FontFile] = []
    for name in fallback:
        p = _first(dirs, name)
        if p is not None and (regular is None or p != regular.path) and all(f.path != p for f in fallbacks):
            fallbacks.append(FontFile(p, 0))
    found = FontPaths(regular, bold, tuple(fallbacks))
    log.info("report PDF fonts: %s (bold %s), %d fallback font(s)",
             regular.path if regular else "built-in Helvetica", bold.path if bold else "-", len(fallbacks))
    return found


def _search_linux_dejavu(dirs: Sequence[Path]) -> FontFile | None:
    for d in dirs:
        try:
            for p in d.rglob("DejaVuSans.ttf"):
                return FontFile(p, 0)
        except OSError:
            continue
    return None


@lru_cache(maxsize=32)
def _cmap(path: Path, index: int) -> frozenset[int]:
    try:
        from fontTools.ttLib import TTFont

        font = TTFont(str(path), fontNumber=index, lazy=True)
        try:
            return frozenset((font.getBestCmap() or {}).keys())
        finally:
            font.close()
    except Exception as exc:  # noqa: BLE001 - an unreadable fallback font just covers nothing
        log.debug("cannot read cmap of %s: %s", path, exc)
        return frozenset()


_ASCII = {
    "\u2264": "<=", "\u2265": ">=", "\u2192": "->", "\u2190": "<-", "\u2194": "<->", "\u21d2": "=>",
    "\u2212": "-", "\u2010": "-", "\u2011": "-", "\u2012": "-", "\u2015": "-", "\u2043": "-",
    "\u2032": "'", "\u2033": '"', "\u2044": "/", "\u2248": "~", "\u2260": "!=", "\u00a0": " ",
    "\u2002": " ", "\u2003": " ", "\u2009": " ", "\u202f": " ", "\u25cf": "*", "\u25cb": "o",
    "\u2219": "*",
}


class _FontKit:
    """Registers the fonts on one FPDF document and makes any text safe to draw with them."""

    def __init__(self, pdf: FPDF, paths: FontPaths) -> None:
        self.pdf = pdf
        self.unicode = paths.regular is not None
        self._pending = list(paths.fallbacks)
        self._registered: list[tuple[str, frozenset[int]]] = []
        self._chars: dict[str, str] = {}
        if paths.regular is not None:
            bold = paths.bold or paths.regular
            pdf.add_font(_FAMILY, "", str(paths.regular.path), collection_font_number=paths.regular.index)
            pdf.add_font(_FAMILY, "B", str(bold.path), collection_font_number=bold.index)
            self.family = _FAMILY
            self._covered = frozenset(pdf.fonts[_FAMILY].cmap) & frozenset(pdf.fonts[_FAMILY + "B"].cmap)
        else:
            self.family = _CORE_FAMILY
            self._covered = frozenset()
            pdf.core_fonts_encoding = "windows-1252"

    def clean(self, text: Any) -> str:
        if text is None:
            return ""
        s = unicodedata.normalize("NFC", str(text))
        out = []
        for ch in s:
            r = self._chars.get(ch)
            if r is None:
                r = self._resolve(ch)
                self._chars[ch] = r
            out.append(r)
        return "".join(out)

    def _resolve(self, ch: str) -> str:
        if ch == "\n":
            return "\n"
        if ch in "\t\x0b\x0c":
            return " "
        cp = ord(ch)
        cat = unicodedata.category(ch)
        if cat in ("Zl", "Zp"):
            return "\n"
        if cat in ("Cc", "Cf", "Cs", "Co", "Cn") or 0xFE00 <= cp <= 0xFE0F or 0xE0100 <= cp <= 0xE01EF \
                or 0x1F3FB <= cp <= 0x1F3FF:
            return ""
        if self.unicode:
            if cp in self._covered or self._fallback_covers(cp):
                return ch
            if cat in ("Mn", "Me", "Mc"):
                return ""
            if cat == "Zs":
                return " "
            return self._replacement(ch)
        if _cp1252(ch):
            return ch
        if ch in _ASCII:
            return _ASCII[ch]
        if cat in ("Mn", "Me", "Mc"):
            return ""
        if cat == "Zs":
            return " "
        base = "".join(c for c in unicodedata.normalize("NFKD", ch) if not unicodedata.combining(c))
        if base and all(_cp1252(c) for c in base):
            return base
        return self._replacement(ch)

    def _replacement(self, ch: str) -> str:
        if unicodedata.category(ch).startswith("S"):
            name = unicodedata.name(ch, "")
            if name:
                return f"[{name.lower()}]"
        return "?"

    def _fallback_covers(self, cp: int) -> bool:
        for _, cmap in self._registered:
            if cp in cmap:
                return True
        for i, ff in enumerate(self._pending):
            if cp in _cmap(ff.path, ff.index):
                del self._pending[i]
                name = f"tdfb{len(self._registered)}"
                try:
                    self.pdf.add_font(name, "", str(ff.path), collection_font_number=ff.index)
                except Exception as exc:  # noqa: BLE001 - skip a fallback font fpdf2 cannot use
                    log.warning("fallback font %s unusable: %s", ff.path, exc)
                    return False
                cmap = frozenset(self.pdf.fonts[name].cmap)
                self._registered.append((name, cmap))
                self.pdf.set_fallback_fonts([n for n, _ in self._registered], exact_match=False)
                return cp in cmap
        return False


def _cp1252(ch: str) -> bool:
    try:
        ch.encode("cp1252")
    except UnicodeEncodeError:
        return False
    return True


