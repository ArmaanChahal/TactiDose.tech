"""PDF rendering of a report with fpdf2 (offline, Windows / macOS / Linux).

Layout (US Letter, portrait): title block (patient, period, generated at/by, device), summary
tiles, adherence-by-day bar chart drawn with fpdf2 primitives + the same numbers as a table,
per-medication table, missed / failed / uncertain list, refused requests, inventory, the
narrative, timestamped conversation excerpts (patient vs assistant), an "About this report"
section with definitions, and on every page the footer disclaimer
``Prototype — not a medical device. Generated by TactiDose.`` plus "Page X of Y".

Readability: 11 pt body text (9–10 pt in tables), black-on-white, state is always written as
words (never colour alone), the chart has direct labels for the days that matter and a table
twin, and the PDF has a title, language and an outline (bookmarks per section).

Unicode: a TrueType font from the OS is embedded when one is found (Arial / Segoe UI /
Calibri on Windows, DejaVu / Liberation / Noto on Linux, Arial / Arial Unicode / Helvetica on
macOS). Characters it lacks are drawn from OS fallback fonts registered on demand (symbols and
emoji outlines, CJK, Korean, Indic...), otherwise replaced: symbols by their Unicode name
("[nauseated face]"), anything else by "?". Variation selectors, joiners and skin-tone
modifiers are dropped. Without any TTF font (or if rendering with it fails) the built-in
Helvetica is used and text is sanitised to its Windows-1252 (latin-1 superset) encoding.
"""

