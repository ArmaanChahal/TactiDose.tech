    def _chart(self, rows: Sequence[dict[str, Any]]) -> None:
        pdf = self.pdf
        n = len(rows)
        axis_w, plot_h, top_pad, band = 12.0, 42.0, 6.0, 9.0
        self._ensure(top_pad + plot_h + band + 4)
        plot_x = pdf.l_margin + axis_w
        plot_w = pdf.epw - axis_w
        y_top = pdf.get_y() + top_pad
        base = y_top + plot_h
        pdf.set_line_width(0.2)
        pdf.set_draw_color(*GRID)
        for pct in (25, 50, 75, 100):
            y = base - plot_h * pct / 100
            pdf.line(plot_x, y, plot_x + plot_w, y)
        self._font(8, False, INK2)
        for pct in (0, 25, 50, 75, 100):
            y = base - plot_h * pct / 100
            pdf.set_xy(pdf.l_margin, y - 1.6)
            pdf.cell(axis_w - 2, 3.2, f"{pct}%", align="R")
        if n:
            slot = plot_w / n
            bar_w = min(slot * 0.6, 6.35)            # 24 px cap
            every = max(1, math.ceil(n / 12))
            labelled = _bars_to_label(rows)
            for i, r in enumerate(rows):
                cx = plot_x + slot * (i + 0.5)
                rate = r["adherence_rate"]
                if rate is not None and rate > 0:
                    h = plot_h * min(rate, 1.0)
                    pdf.set_fill_color(*BAR)
                    radius = max(0.0, min(1.0, bar_w / 2, h))
                    pdf.rect(cx - bar_w / 2, base - h, bar_w, h, style="F",
                             round_corners=("TOP_LEFT", "TOP_RIGHT") if radius > 0 else False,
                             corner_radius=radius)
                elif rate is None:
                    pdf.set_draw_color(*MUTED)
                    pdf.set_line_width(0.4)
                    half = max(bar_w / 3, 0.4)
                    pdf.line(cx - half, base - 1.2, cx + half, base - 1.2)
                if i in labelled and rate is not None:
                    self._font(8, True)
                    text = fmt_pct(rate)
                    tw = pdf.get_string_width(text) + 1
                    pdf.set_xy(cx - tw / 2, base - plot_h * min(rate, 1.0) - 4.4)
                    pdf.cell(tw, 3.6, text, align="C")
                if (n - 1 - i) % every == 0:
                    self._font(7.5, False, INK2)
                    day = datetime.fromisoformat(r["date"])
                    text = f"{r['weekday']} {day.day}"
                    lw = slot * every
                    pdf.set_xy(cx - lw / 2, base + 1.5)
                    pdf.cell(lw, 3.6, text, align="C")
        pdf.set_draw_color(*AXIS)
        pdf.set_line_width(0.3)
        pdf.line(plot_x, base, plot_x + plot_w, base)
        pdf.set_xy(pdf.l_margin, base + band)
        self._font(11)

