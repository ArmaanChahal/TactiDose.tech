@dataclass(frozen=True)
class FontFile:
    path: Path
    index: int = 0          # face number inside a .ttc collection


@dataclass(frozen=True)
class FontPaths:
    """Fonts to embed. ``regular=None`` means the built-in Helvetica (cp1252 text only)."""

    regular: FontFile | None = None
    bold: FontFile | None = None
    fallbacks: tuple[FontFile, ...] = ()


def _win_dirs() -> list[Path]:
    root = os.environ.get("WINDIR") or os.environ.get("SystemRoot") or r"C:\Windows"
    dirs = [Path(root) / "Fonts"]
    local = os.environ.get("LOCALAPPDATA")
    if local:
        dirs.append(Path(local) / "Microsoft" / "Windows" / "Fonts")
    return dirs


def _home() -> Path | None:
    try:
        return Path.home()
    except (RuntimeError, KeyError, OSError):   # no resolvable home directory (service accounts)
        return None


def _linux_dirs() -> list[Path]:
    home = _home()
    user = [home / ".local" / "share" / "fonts", home / ".fonts"] if home else []
    return [Path("/usr/share/fonts"), Path("/usr/local/share/fonts"), *user]


def _mac_dirs() -> list[Path]:
    home = _home()
    user = [home / "Library" / "Fonts"] if home else []
    return [Path("/System/Library/Fonts/Supplemental"), Path("/Library/Fonts"), Path("/System/Library/Fonts"), *user]


