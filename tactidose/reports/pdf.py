class _ReportPDF(FPDF):
    def __init__(self) -> None:
        super().__init__(orientation="P", unit="mm", format="Letter")
        self.kit: _FontKit | None = None
        self.running_header = ""
        self._fitted_header: str | None = None
        self.footer_text = ""

    def header(self) -> None:
        if self.page_no() == 1 or self.kit is None:
            return
        self.set_y(8)
        self.set_font(self.kit.family, "", 9)
        self.set_text_color(*INK2)
        if self._fitted_header is None:
            self._fitted_header = _fit_text(self, self.running_header, self.epw)
        self.cell(0, 5, self._fitted_header, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.set_draw_color(*GRID)
        self.set_line_width(0.2)
        self.line(self.l_margin, 14, self.w - self.r_margin, 14)
        self.set_y(self.t_margin)
        self.set_text_color(*INK)

    def footer(self) -> None:
        if self.kit is None:
            return
        self.set_y(-14)
        self.set_draw_color(*GRID)
        self.set_line_width(0.2)
        self.line(self.l_margin, self.get_y(), self.w - self.r_margin, self.get_y())
        self.set_y(-12.5)
        self.set_font(self.kit.family, "", 9)
        self.set_text_color(*INK2)
        page = f"Page {self.page_no()} of {{nb}}"
        width = self.epw - 30
        self.cell(width, 5, self.footer_text, align="L")
        self.cell(30, 5, page, align="R")
        self.set_text_color(*INK)


def render_report_pdf(
    data: ReportData,
    stats: dict[str, Any],
    narrative: Narrative,
    excerpts: Sequence[Excerpt] = (),
    *,
    fonts: FontPaths | None = None,
) -> bytes:
    """Render the report; returns the PDF bytes. Retries with the built-in font if the TTF path fails."""
    paths = fonts if fonts is not None else find_system_fonts()
    if paths.regular is not None:
        try:
            return _Renderer(data, stats, narrative, excerpts, paths).render()
        except Exception as exc:  # noqa: BLE001 - font trouble must not cost the report
            log.warning("PDF rendering with %s failed (%s: %s); retrying with the built-in font",
                        paths.regular.path, type(exc).__name__, exc)
    return _Renderer(data, stats, narrative, excerpts, FontPaths()).render()


class _Renderer:
    def __init__(self, data: ReportData, stats: dict[str, Any], narrative: Narrative,
                 excerpts: Sequence[Excerpt], paths: FontPaths) -> None:
        self.data = data
        self.stats = stats
        self.narrative = narrative
        self.excerpts = list(excerpts)
        self.pdf = _ReportPDF()
        self.kit = _FontKit(self.pdf, paths)
        self.t: Callable[[Any], str] = self.kit.clean
        self.pdf.kit = self.kit

    # ------------------------------------------------------------------ top level
    def render(self) -> bytes:
        pdf, d = self.pdf, self.data
        start, end = d.local(d.period_start), d.local(d.period_end)
        period_short = f"{fmt_date(start)} – {fmt_date(end)}"
        pdf.running_header = self.t(f"TactiDose report — {d.patient.display_name} — {period_short}")
        pdf.footer_text = self.t(DISCLAIMER)
        pdf.set_margins(16, 16, 16)
        pdf.set_auto_page_break(True, margin=_BOTTOM_MARGIN)
        pdf.set_title(f"TactiDose report — {d.patient.display_name} — last {_days(d.days)}")
        pdf.set_author("TactiDose")
        pdf.set_creator("TactiDose")
        pdf.set_subject("Pill drop and adherence report (prototype, not a medical device)")
        pdf.set_keywords("TactiDose, report, adherence, pill drops")
        pdf.set_lang("en")
        try:
            pdf.set_creation_date(d.generated_at)
        except Exception as exc:  # noqa: BLE001 - metadata only
            log.debug("PDF creation date not set: %s", exc)
        pdf.add_page()
        self._title_block()
        self._summary()
        self._adherence()
        self._medications()
        self._issues()
        self._refused()
        self._inventory()
        self._narrative()
        self._excerpts()
        self._about()
        return bytes(pdf.output())

    # ------------------------------------------------------------------ primitives
    def _font(self, size: float, bold: bool = False, color: tuple[int, int, int] = INK) -> None:
        self.pdf.set_font(self.kit.family, "B" if bold else "", size)
        self.pdf.set_text_color(*color)

    def _para(self, text: str, *, size: float = 11, bold: bool = False, color: tuple[int, int, int] = INK,
              indent: float = 0.0, line_h: float | None = None, gap: float = 1.0) -> None:
        pdf = self.pdf
        self._font(size, bold, color)
        pdf.set_x(pdf.l_margin + indent)
        pdf.multi_cell(pdf.epw - indent, line_h or size * 0.53, self.t(text), align="L",
                       new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        if gap:
            pdf.ln(gap)

    def _note(self, text: str) -> None:
        self._para(text, size=9.5, color=INK2, gap=1.5)

    def _ensure(self, height: float) -> None:
        if self.pdf.will_page_break(height):
            self.pdf.add_page()

    def _heading(self, text: str, *, keep: float = 48.0) -> None:
        pdf = self.pdf
        self._ensure(keep)
        if pdf.get_y() > pdf.t_margin + 1:
            pdf.ln(3)
        pdf.start_section(text)
        self._font(15, True)
        pdf.cell(0, 8, self.t(text), new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.ln(1)

    def _table(self, headers: Sequence[str], rows: Sequence[Sequence[Any]], widths: Sequence[float],
               aligns: Sequence[str], *, size: float = 9, empty: str = "None in this period.",
               width: float | None = None) -> None:
        pdf = self.pdf
        if not rows:
            self._note(empty)
            return
        shown = list(rows[:_MAX_TABLE_ROWS])
        head = [self.t(h) for h in headers]
        body = [[self.t("–" if v is None or v == "" else v) for v in r] for r in shown]
        total = min(width or pdf.epw, pdf.epw)
        col_widths = self._fit_widths(head, body, widths, total, size)
        self._font(size)
        pdf.set_fill_color(0)   # fpdf2 tables inherit a non-default fill colour as every cell's background
        pdf.set_draw_color(*AXIS)
        pdf.set_line_width(0.2)
        with pdf.table(
            col_widths=tuple(col_widths),
            text_align=tuple(aligns),
            width=total,
            align="LEFT",
            line_height=size * 0.5,
            padding=(1.0, _CELL_PAD),
            borders_layout="HORIZONTAL_LINES",
            headings_style=FontFace(emphasis="BOLD", color=INK, fill_color=TILE),
        ) as table:
            row = table.row()
            for h in head:
                row.cell(h)
            for r in body:
                row = table.row()
                for value in r:
                    row.cell(value)
        pdf.ln(2)
        if len(rows) > len(shown):
            self._note(f"{len(rows) - len(shown)} more rows are not shown.")

    def _fit_widths(self, head: Sequence[str], body: Sequence[Sequence[str]], weights: Sequence[float],
                    total: float, size: float) -> list[float]:
        """Column widths (mm) summing to ``total``: never narrower than the longest word of the heading or
        of a cell (capped), so words do not break mid-word; spare width follows ``weights``."""
        pdf = self.pdf
        pad = 2 * _CELL_PAD + 0.8
        mins = []
        for j, h in enumerate(head):
            self._font(size, True)
            need = max((pdf.get_string_width(w) for w in h.split()), default=0.0)
            self._font(size)
            for r in body:
                if j < len(r):
                    need = max(need, max((pdf.get_string_width(w) for w in r[j].split()), default=0.0))
            mins.append(min(need, _MAX_WORD_MM) + pad)
        spare = total - sum(mins)
        if spare <= 0:
            return [m * total / sum(mins) for m in mins]
        wsum = sum(weights) or 1.0
        return [m + spare * w / wsum for m, w in zip(mins, weights)]

    def _local(self, dt: datetime) -> datetime:
        return self.data.local(dt)

    # ------------------------------------------------------------------ sections
    def _title_block(self) -> None:
        pdf, d = self.pdf, self.data
        start, end = self._local(d.period_start), self._local(d.period_end)
        gen = self._local(d.generated_at)
        self._font(22, True)
        pdf.cell(0, 11, self.t("TactiDose report"), new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self._para(f"{d.patient.display_name} · Patient ID {d.patient.user_id}", size=14, bold=True, gap=1.5)
        self._para(f"Period: {fmt_date(start)}, {fmt_time(start)} – {fmt_date(end)}, {fmt_time(end)} "
                   f"({d.timezone}) · last {_days(d.days)}", gap=0.5)
        by = d.creator
        who = f" by {by.display_name} ({by.role})" if by is not None else ""
        self._para(f"Generated: {fmt_date(gen)}, {fmt_time(gen)}{who}", gap=0.5)
        dev = d.device
        if dev is not None:
            minutes = dev.manual_cooldown_minutes
            cooldown = (f"{minutes} minute{'' if minutes == 1 else 's'}" if minutes else "off")
            self._para(f"Device: {dev.name} ({dev.device_id}) · Cooldown after any drop: {cooldown} · "
                       f"Automatic scheduled drops: {'on' if dev.auto_drop_enabled else 'off'}",
                       size=10, color=INK2, gap=0.5)
        else:
            self._para("Device: none linked to this patient.", size=10, color=INK2, gap=0.5)
        pdf.ln(2)
        pdf.set_draw_color(*AXIS)
        pdf.set_line_width(0.3)
        pdf.line(pdf.l_margin, pdf.get_y(), pdf.w - pdf.r_margin, pdf.get_y())
        pdf.ln(3)

    def _summary(self) -> None:
        s = self.stats
        doses, drops = s["doses"], s["drops"]
        self._heading("Summary", keep=75)
        decided = doses["dispensed"] + doses["missed"]
        adherence_caption = (f"{doses['dispensed']} of {decided} scheduled doses dropped" if decided
                             else "No scheduled doses decided yet")
        open_doses = doses["pending"] + doses["hardware_errors"]
        missed_caption = "Not dropped within their window"
        if open_doses:
            missed_caption += f" · {open_doses} still open"
        refused = drops["refused_by_reason"]
        refused_caption = " · ".join(f"{reason_label(r)} {n}" for r, n in list(refused.items())[:2]) or "None"
        problems = drops["failed"] + drops["uncertain"]
        problem_caption = f"{drops['failed']} failed · {drops['uncertain']} uncertain"
        if drops["needs_review"]:
            problem_caption += f" · {drops['needs_review']} to review"
        tiles = [
            ("Adherence", fmt_pct(doses["adherence_rate"]), adherence_caption),
            ("On time", str(doses["on_time"]),
             f"Within {s.get('on_time_minutes', 15)} min of schedule · {doses['late']} late"),
            ("Missed doses", str(doses["missed"]), missed_caption),
            ("Drops on request", str(drops["on_request_drops"]),
             (f"{drops['manual_drops']} app · {drops['agent_drops']} assistant · "
              f"{drops['button_drops']} device button")),
            ("Refused requests", str(drops["refused_requests"]), refused_caption),
            ("Drop problems", str(problems), problem_caption),
        ]
        pdf = self.pdf
        gap = 4.0
        w = (pdf.epw - 2 * gap) / 3
        h = 30.0
        y = pdf.get_y()
        for i, (label, value, caption) in enumerate(tiles):
            col, row = i % 3, i // 3
            self._tile(pdf.l_margin + col * (w + gap), y + row * (h + gap), w, h, label, value, caption)
        pdf.set_xy(pdf.l_margin, y + 2 * h + gap + 3)

    def _tile(self, x: float, y: float, w: float, h: float, label: str, value: str, caption: str) -> None:
        pdf = self.pdf
        pdf.set_fill_color(*TILE)
        pdf.rect(x, y, w, h, style="F", round_corners=True, corner_radius=1.5)
        pdf.set_xy(x + 4, y + 3)
        self._font(10, True, INK2)
        pdf.cell(w - 8, 5, self.t(label))
        pdf.set_xy(x + 4, y + 8.5)
        self._font(22, True)
        pdf.cell(w - 8, 10, self.t(value))
        self._font(9, False, INK2)
        lines = pdf.multi_cell(w - 8, 4.2, self.t(caption), align="L", dry_run=True, output="LINES")
        if len(lines) > 2:
            lines = [lines[0], lines[1].rstrip() + "…"]
        for j, line in enumerate(lines):
            pdf.set_xy(x + 4, y + 20 + j * 4.2)
            pdf.cell(w - 8, 4.2, line)

